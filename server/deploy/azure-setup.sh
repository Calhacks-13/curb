#!/usr/bin/env bash
set -euo pipefail

# --- Configuration ---
RG="curb-test-rg"
LOCATION="eastus"
COSMOS_ACCOUNT="curb-cosmos-$(openssl rand -hex 4)"
SIGNALR_NAME="curb-signalr-$(openssl rand -hex 4)"
DB_NAME="curb"

echo "=== Curb Azure Provisioning ==="
echo "Resource Group: $RG"
echo "Location:       $LOCATION"

# 1. Resource Group
echo "--- Creating resource group..."
az group create --name "$RG" --location "$LOCATION" --output none

# 2. Cosmos DB Account (GlobalDocumentDB, Session consistency)
echo "--- Creating Cosmos DB account: $COSMOS_ACCOUNT (this takes ~5 min)..."
az cosmosdb create \
  --name "$COSMOS_ACCOUNT" \
  --resource-group "$RG" \
  --kind GlobalDocumentDB \
  --default-consistency-level Session \
  --locations regionName="$LOCATION" failoverPriority=0 \
  --output none

# 3. Database
echo "--- Creating database: $DB_NAME..."
az cosmosdb sql database create \
  --account-name "$COSMOS_ACCOUNT" \
  --resource-group "$RG" \
  --name "$DB_NAME" \
  --output none

# 4. Container: blocks (partition /segment_id, TTL, spatial index on /location)
echo "--- Creating container: blocks..."
az cosmosdb sql container create \
  --account-name "$COSMOS_ACCOUNT" \
  --resource-group "$RG" \
  --database-name "$DB_NAME" \
  --name "blocks" \
  --partition-key-path "/segment_id" \
  --default-ttl -1 \
  --idx '{
    "indexingMode": "consistent",
    "includedPaths": [{"path": "/*"}],
    "excludedPaths": [{"path": "/\"_etag\"/?"}],
    "spatialIndexes": [{"path": "/location/*", "types": ["Point"]}]
  }' \
  --output none

# 5. Container: signs (partition /grid_key, spatial index on /location)
echo "--- Creating container: signs..."
az cosmosdb sql container create \
  --account-name "$COSMOS_ACCOUNT" \
  --resource-group "$RG" \
  --database-name "$DB_NAME" \
  --name "signs" \
  --partition-key-path "/grid_key" \
  --idx '{
    "indexingMode": "consistent",
    "includedPaths": [{"path": "/*"}],
    "excludedPaths": [{"path": "/\"_etag\"/?"}],
    "spatialIndexes": [{"path": "/location/*", "types": ["Point"]}]
  }' \
  --output none

# 6. Azure SignalR Service (Free tier, Serverless mode)
echo "--- Creating SignalR service: $SIGNALR_NAME..."
az signalr create \
  --name "$SIGNALR_NAME" \
  --resource-group "$RG" \
  --sku Free_F1 \
  --service-mode Serverless \
  --location "$LOCATION" \
  --output none

# 7. Extract connection strings
echo "--- Extracting credentials..."
COSMOS_ENDPOINT=$(az cosmosdb show --name "$COSMOS_ACCOUNT" --resource-group "$RG" --query "documentEndpoint" -o tsv)
COSMOS_KEY=$(az cosmosdb keys list --name "$COSMOS_ACCOUNT" --resource-group "$RG" --query "primaryMasterKey" -o tsv)
SIGNALR_CONN=$(az signalr key list --name "$SIGNALR_NAME" --resource-group "$RG" --query "primaryConnectionString" -o tsv)

# 8. Generate .env file
ENV_FILE="$(dirname "$0")/../.env"
cat > "$ENV_FILE" <<EOF
# Auto-generated by azure-setup.sh — $(date -Iseconds)
CURB_COSMOS_ENDPOINT=$COSMOS_ENDPOINT
CURB_COSMOS_KEY=$COSMOS_KEY
CURB_COSMOS_DATABASE=$DB_NAME
CURB_COSMOS_BLOCKS_CONTAINER=blocks
CURB_COSMOS_SIGNS_CONTAINER=signs
CURB_SIGNALR_CONNECTION_STRING=$SIGNALR_CONN
CURB_ANTHROPIC_API_KEY=
CURB_VEHICLE_MODEL_PATH=yolov8m.pt
EOF

echo ""
echo "=== Done! ==="
echo "Cosmos account:  $COSMOS_ACCOUNT"
echo "SignalR service:  $SIGNALR_NAME"
echo ".env written to:  $ENV_FILE"
echo ""
echo "Next: set CURB_ANTHROPIC_API_KEY in .env, then run your server."
